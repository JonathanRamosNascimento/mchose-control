//! PipeWire integration: renders filter-chain / echo-cancel configs, manages the
//! systemd *user* services that host them, pushes live parameter updates and
//! talks to the hardware nodes (volume / mute).
//!
//! Playback processing runs as a WirePlumber *smart filter*: it is linked in front
//! of the headset automatically while the headset is present, and disappears from
//! the path when the receiver is unplugged. The default sink is never changed.

use std::collections::BTreeMap;
