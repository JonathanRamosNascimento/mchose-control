fn config_home() -> PathBuf {
    std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|p| p.is_absolute())
        .unwrap_or_else(|| PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join(".config"))
}

pub fn app_config_dir() -> PathBuf {
    config_home().join("mchose")
}

fn find_in_path(bin: &str) -> PathBuf {
    std::env::var_os("PATH")
        .into_iter()
        .flat_map(|p| std::env::split_paths(&p).collect::<Vec<_>>())
        .map(|d| d.join(bin))
        .find(|p| p.is_file())
        .unwrap_or_else(|| PathBuf::from("/usr/bin").join(bin))
}

pub(crate) fn write_atomic(path: &Path, contents: &str) -> io::Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    if fs::read_to_string(path).is_ok_and(|old| old == contents) {
        return Ok(());
    }
    let tmp = path.with_extension("tmp");
    fs::write(&tmp, contents)?;
    fs::rename(tmp, path)
}

/// One PipeWire helper process managed as a systemd user unit.
#[derive(Debug, Clone)]
pub struct Service {
    pub unit: &'static str,
    pub description: &'static str,
    pub conf_path: PathBuf,
}

impl Service {
    pub fn dsp() -> Self {
        Self {
            unit: DSP_UNIT,
            description: "equalizador e efeitos de áudio",
            conf_path: app_config_dir().join("pipewire").join("mchose-dsp.conf"),
        }
    }

    pub fn mic() -> Self {
        Self {
            unit: MIC_UNIT,
            description: "redução de ruído do microfone",
            conf_path: app_config_dir().join("pipewire").join("mchose-mic.conf"),
        }
    }

    pub fn unit_path(&self) -> PathBuf {
        config_home().join("systemd").join("user").join(self.unit)
    }

    pub fn render_unit(&self) -> String {
        format!(
            "# Generated by MCHOSE Control\n\
             [Unit]\n\
             Description=MCHOSE Control — {}\n\
             After=pipewire.service wireplumber.service\n\
             BindsTo=pipewire.service\n\
             \n\
             [Service]\n\
             Type=simple\n\
             ExecStart=\"{}\" -c \"{}\"\n\
             Restart=on-failure\n\
             RestartSec=2\n\
             Slice=session.slice\n\
             \n\
             [Install]\n\
             WantedBy=pipewire.service\n",
            self.description,
            find_in_path("pipewire").display(),
            self.conf_path.display()
        )
    }

    /// Writes the config (and the unit if needed). Returns true if the config changed.
    pub fn write_config(&self, conf: &str) -> io::Result<bool> {
        let changed = fs::read_to_string(&self.conf_path).map_or(true, |old| old != conf);
        write_atomic(&self.conf_path, conf)?;
        let unit = self.render_unit();
        if fs::read_to_string(self.unit_path()).map_or(true, |old| old != unit) {
            write_atomic(&self.unit_path(), &unit)?;
            systemctl(&["daemon-reload"])?;
        }
        Ok(changed)
    }

    pub fn is_active(&self) -> bool {
        run("systemctl", &["--user", "is-active", "--quiet", self.unit]).is_ok_and(|o| o.status.success())
    }

    pub fn is_enabled(&self) -> bool {
        run("systemctl", &["--user", "is-enabled", "--quiet", self.unit]).is_ok_and(|o| o.status.success())
    }

    /// Enable at login and start now.
    pub fn enable_now(&self) -> io::Result<()> {
        systemctl(&["enable", "--now", self.unit])
    }

    /// Stop and remove from autostart.
    pub fn disable_now(&self) -> io::Result<()> {
        if !self.unit_path().exists() {
            return Ok(());
        }
        systemctl(&["disable", "--now", self.unit])
    }

    pub fn restart(&self) -> io::Result<()> {
        systemctl(&["restart", self.unit])
    }

    /// Removes unit and config files completely.
    pub fn uninstall(&self) -> io::Result<()> {
        let _ = self.disable_now();
        let _ = fs::remove_file(self.unit_path());
        let _ = fs::remove_file(&self.conf_path);
        systemctl(&["daemon-reload"])
    }
}

fn systemctl(args: &[&str]) -> io::Result<()> {
    let mut full = vec!["--user"];
    full.extend_from_slice(args);
    let out = run("systemctl", &full)?;
    if out.status.success() {
        Ok(())
    } else {
        Err(io::Error::other(format!("systemctl {}: {}", args.join(" "), String::from_utf8_lossy(&out.stderr).trim())))
    }
}

