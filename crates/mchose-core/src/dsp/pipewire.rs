const CONTEXT_HEADER: &str = r#"# Generated by MCHOSE Control — edits will be overwritten.
context.properties = {
    log.level = 0
}
context.spa-libs = {
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}
"#;

const BASE_MODULES: &str = r#"    { name = libpipewire-module-rt flags = [ ifexists nofail ] }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
"#;

fn spa_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Renders the playback DSP (filter-chain smart filter) configuration.
pub fn render_dsp_config(s: &DspSettings, card_name: Option<&str>) -> String {
    let card = card_name.filter(|c| !c.is_empty()).unwrap_or(DEFAULT_CARD);
    // Group initial control values per node.
    let mut per_node: BTreeMap<String, Vec<(String, f32)>> = BTreeMap::new();
    for (k, v) in s.controls(SAMPLE_RATE) {
        let (node, port) = k.split_once(':').expect("control has node:port form");
        per_node.entry(node.to_string()).or_default().push((port.to_string(), v));
    }
    let controls = |node: &str| -> String {
        per_node
            .get(node)
            .map(|v| v.iter().map(|(p, val)| format!("{} = {val:.6}", spa_str(p))).collect::<Vec<_>>().join(" "))
            .unwrap_or_default()
    };

    let mut nodes = String::new();
    let mut links = String::new();
    for (ch, other) in [("L", "R"), ("R", "L")] {
        let node = |nodes: &mut String, name: String, label: &str| {
            let _ = writeln!(
                nodes,
                "                    {{ type = builtin name = {name} label = {label} control = {{ {} }} }}",
                controls(&name)
            );
        };
        node(&mut nodes, format!("pre{ch}"), "linear");
        for i in 0..EQ_FREQS.len() {
            node(&mut nodes, format!("eq{ch}{i}"), "bq_peaking");
        }
        node(&mut nodes, format!("bass{ch}"), "bq_lowshelf");
        node(&mut nodes, format!("clar{ch}"), "bq_highshelf");
        let _ = writeln!(nodes, "                    {{ type = builtin name = cp{ch} label = copy }}");
        let _ = writeln!(
            nodes,
            "                    {{ type = builtin name = lp{ch} label = bq_lowpass control = {{ \"Freq\" = {CROSSFEED_LOWPASS_HZ:.1} \"Q\" = 0.5 }} }}"
        );
        let _ = writeln!(
            nodes,
            "                    {{ type = builtin name = dl{ch} label = delay config = {{ \"max-delay\" = 0.01 }} control = {{ \"Delay (s)\" = {CROSSFEED_DELAY_S:.6} }} }}"
        );
        node(&mut nodes, format!("mix{ch}"), "mixer");

        let mut chain = vec![format!("pre{ch}")];
        chain.extend((0..EQ_FREQS.len()).map(|i| format!("eq{ch}{i}")));
        chain.extend([format!("bass{ch}"), format!("clar{ch}"), format!("cp{ch}")]);
        for w in chain.windows(2) {
            let _ = writeln!(links, "                    {{ output = \"{}:Out\" input = \"{}:In\" }}", w[0], w[1]);
        }
        let _ = writeln!(links, "                    {{ output = \"cp{ch}:Out\" input = \"mix{ch}:In 1\" }}");
        let _ = writeln!(links, "                    {{ output = \"cp{ch}:Out\" input = \"lp{ch}:In\" }}");
        let _ = writeln!(links, "                    {{ output = \"lp{ch}:Out\" input = \"dl{ch}:In\" }}");
        let _ = writeln!(links, "                    {{ output = \"dl{ch}:Out\" input = \"mix{other}:In 2\" }}");
    }

    let mut c = String::from(CONTEXT_HEADER);
    let _ = write!(
        c,
        r#"context.modules = [
{BASE_MODULES}    {{ name = libpipewire-module-filter-chain
        args = {{
            node.description = {desc}
            media.name       = {desc}
            filter.graph = {{
                nodes = [
{nodes}                ]
                links = [
{links}                ]
                inputs  = [ "preL:In" "preR:In" ]
                outputs = [ "mixL:Out" "mixR:Out" ]
            }}
            audio.channels = 2
            audio.position = [ FL FR ]
            capture.props = {{
                node.name = "{DSP_NODE}"
                media.class = Audio/Sink
                priority.session = 0
                priority.driver = 0
                filter.smart = true
                filter.smart.name = "mchose-dsp"
                filter.smart.target = {{ api.alsa.card.name = {card_q} media.class = "Audio/Sink" }}
            }}
            playback.props = {{
                node.name = "{DSP_NODE}.output"
                node.passive = true
                stream.dont-remix = true
            }}
        }}
    }}
]
"#,
        desc = spa_str(&format!("{card} · Equalizador")),
        card_q = spa_str(card),
    );
    c
}

/// Renders the microphone processing (WebRTC noise suppression) configuration.
pub fn render_mic_config(m: &MicSettings, source_node: Option<&str>, card_name: Option<&str>) -> String {
    let card = card_name.filter(|c| !c.is_empty()).unwrap_or(DEFAULT_CARD);
    let target = source_node.map(|n| format!("target.object = {}\n                ", spa_str(n))).unwrap_or_default();
    let b = |v: bool| if v { "true" } else { "false" };
    let mut c = String::from(CONTEXT_HEADER);
    let _ = write!(
        c,
        r#"context.modules = [
{BASE_MODULES}    {{ name = libpipewire-module-echo-cancel
        args = {{
            library.name = aec/libspa-aec-webrtc
            monitor.mode = true
            audio.channels = 1
            audio.position = [ MONO ]
            aec.args = {{
                webrtc.noise_suppression = {ns}
                webrtc.gain_control = {agc}
                webrtc.high_pass_filter = {hp}
                webrtc.transient_suppression = {ts}
                webrtc.voice_detection = false
            }}
            capture.props = {{
                node.name = "{MIC_NODE}.capture"
                {target}node.passive = true
            }}
            source.props = {{
                node.name = "{MIC_NODE}"
                node.description = {desc}
                media.class = Audio/Source
            }}
        }}
    }}
]
"#,
        ns = b(m.noise_suppression),
        agc = b(m.gain_control),
        hp = b(m.high_pass),
        ts = b(m.transient_suppression),
        desc = spa_str(&format!("{card} · Microfone limpo")),
    );
    c
}

