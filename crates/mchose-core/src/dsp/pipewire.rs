use serde_json::Value;

use super::settings::{CROSSFEED_DELAY_S, CROSSFEED_LOWPASS_HZ, DspSettings, EQ_FREQS, MicSettings};

pub const SAMPLE_RATE: f32 = 48000.0;

pub const DSP_NODE: &str = "mchose_dsp";
pub const DSP_UNIT: &str = "mchose-dsp.service";
pub const MIC_NODE: &str = "mchose_mic";
pub const MIC_UNIT: &str = "mchose-mic.service";
const DEFAULT_CARD: &str = "MCHOSE V9 PRO";

/// A PipeWire node that belongs to the headset receiver.
#[derive(Debug, Clone, PartialEq)]
pub struct NodeInfo {
    pub id: u32,
    pub name: String,
    pub description: String,
    pub card_name: String,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct HwNodes {
    pub sink: Option<NodeInfo>,
    pub source: Option<NodeInfo>,
}

fn run(cmd: &str, args: &[&str]) -> io::Result<std::process::Output> {
    Command::new(cmd).args(args).stdin(Stdio::null()).output()
}

/// Finds the ALSA sink/source of the receiver by USB vendor/product id.
pub fn find_hw_nodes() -> HwNodes {
    let Ok(out) = run("pw-dump", &["--no-colors"]) else {
        return HwNodes::default();
    };
    let Ok(Value::Array(objs)) = serde_json::from_slice::<Value>(&out.stdout) else {
        return HwNodes::default();
    };
    let props = |o: &Value| o.pointer("/info/props").cloned().unwrap_or(Value::Null);
    let s = |v: &Value, k: &str| v.get(k).and_then(Value::as_str).unwrap_or("").to_string();

    let devices: Vec<u64> = objs
        .iter()
        .filter(|o| o["type"] == "PipeWire:Interface:Device")
        .filter(|o| {
            let p = props(o);
            s(&p, "device.vendor.id").eq_ignore_ascii_case("0x291d")
                && s(&p, "device.product.id").eq_ignore_ascii_case("0x385d")
        })
        .filter_map(|o| o["id"].as_u64())
        .collect();

    let mut nodes = HwNodes::default();
    for o in objs.iter().filter(|o| o["type"] == "PipeWire:Interface:Node") {
        let p = props(o);
        let dev = p.get("device.id").and_then(Value::as_u64);
        if !dev.is_some_and(|d| devices.contains(&d)) {
            continue;
        }
        let info = NodeInfo {
            id: o["id"].as_u64().unwrap_or(0) as u32,
            name: s(&p, "node.name"),
            description: s(&p, "node.description"),
            card_name: s(&p, "api.alsa.card.name"),
        };
        match p.get("media.class").and_then(Value::as_str) {
            Some("Audio/Sink") if nodes.sink.is_none() => nodes.sink = Some(info),
            Some("Audio/Source") if nodes.source.is_none() => nodes.source = Some(info),
            _ => {}
        }
    }
    nodes
}

/// Returns the PipeWire id of a node by name, if it exists.
pub fn node_id(name: &str) -> Option<u32> {
    let out = run("pw-cli", &["info", name]).ok()?;
    if !out.status.success() {
        return None;
    }
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .find_map(|l| l.trim().strip_prefix("id:").and_then(|v| v.trim().parse().ok()))
}

