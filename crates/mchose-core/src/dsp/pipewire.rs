/// Pushes control changes to a running filter-chain node without restarting it.
/// Updates are coalesced so dragging a slider never floods PipeWire.
pub struct LiveControl {
    tx: mpsc::Sender<Vec<(String, f32)>>,
}

impl LiveControl {
    pub fn new(node_name: &'static str) -> Self {
        let (tx, rx) = mpsc::channel::<Vec<(String, f32)>>();
        thread::Builder::new()
            .name("mchose-pw-control".into())
            .spawn(move || {
                let mut last_sent: BTreeMap<String, f32> = BTreeMap::new();
                while let Ok(first) = rx.recv() {
                    let mut pending: BTreeMap<String, f32> = first.into_iter().collect();
                    // Coalesce everything that arrives within a short window.
                    while let Ok(more) = rx.recv_timeout(Duration::from_millis(25)) {
                        pending.extend(more);
                    }
                    pending.retain(|k, v| last_sent.get(k).is_none_or(|old| (old - *v).abs() > 1e-6));
                    if pending.is_empty() {
                        continue;
                    }
                    let mut body = String::from("{ params = [");
                    for (k, v) in &pending {
                        let _ = write!(body, " {} {v:.6}", spa_str(k));
                    }
                    body.push_str(" ] }");
                    match run("pw-cli", &["set-param", node_name, "Props", &body]) {
                        Ok(o) if o.status.success() && !String::from_utf8_lossy(&o.stderr).contains("rror") => {
                            last_sent.extend(pending);
                        }
                        Ok(o) => {
                            log::debug!("pw-cli set-param failed: {}", String::from_utf8_lossy(&o.stderr));
                            last_sent.clear();
                        }
                        Err(e) => {
                            log::warn!("pw-cli: {e}");
                            last_sent.clear();
                        }
                    }
                }
            })
            .expect("spawn pw control thread");
        Self { tx }
    }

    pub fn push(&self, controls: Vec<(String, f32)>) {
        let _ = self.tx.send(controls);
    }
}

// ---------------------------------------------------------------------------
// Hardware volume / mute (via wpctl)
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Volume {
    /// Linear volume, 1.0 = 100 %.
    pub level: f32,
    pub muted: bool,
}

pub fn get_volume(node_id: u32) -> Option<Volume> {
    let out = run("wpctl", &["get-volume", &node_id.to_string()]).ok()?;
    let text = String::from_utf8_lossy(&out.stdout);
    let level = text.split_whitespace().nth(1)?.parse().ok()?;
    Some(Volume { level, muted: text.contains("[MUTED]") })
}

pub fn set_volume(node_id: u32, level: f32) -> io::Result<()> {
    let out = run("wpctl", &["set-volume", &node_id.to_string(), &format!("{:.3}", level.clamp(0.0, 1.0))])?;
    if out.status.success() { Ok(()) } else { Err(io::Error::other("wpctl set-volume failed")) }
}

pub fn set_mute(node_id: u32, muted: bool) -> io::Result<()> {
    let out = run("wpctl", &["set-mute", &node_id.to_string(), if muted { "1" } else { "0" }])?;
    if out.status.success() { Ok(()) } else { Err(io::Error::other("wpctl set-mute failed")) }
}

/// `node.name` of the current default source (`source = true`) or sink.
pub fn default_node_name(source: bool) -> Option<String> {
    let target = if source { "@DEFAULT_AUDIO_SOURCE@" } else { "@DEFAULT_AUDIO_SINK@" };
    let out = run("wpctl", &["inspect", target]).ok()?;
    String::from_utf8_lossy(&out.stdout).lines().find_map(|l| {
        let l = l.trim().trim_start_matches('*').trim();
        l.strip_prefix("node.name = ").map(|v| v.trim_matches('"').to_string())
    })
}

pub fn set_default_node(node_id: u32) -> io::Result<()> {
    let out = run("wpctl", &["set-default", &node_id.to_string()])?;
    if out.status.success() { Ok(()) } else { Err(io::Error::other("wpctl set-default failed")) }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dsp_config_contains_full_graph() {
        let mut s = DspSettings::default();
        s.eq_gains[2] = 4.5;
        let c = render_dsp_config(&s, Some("MCHOSE V9 PRO"));
        assert!(c.contains("filter.smart = true"));
        assert!(
            c.contains(r#"filter.smart.target = { api.alsa.card.name = "MCHOSE V9 PRO" media.class = "Audio/Sink" }"#)
        );
        assert!(c.contains("name = eqL2 label = bq_peaking"));
        assert!(c.contains(r#""Gain" = 4.500000"#));
        assert!(c.contains(r#"{ output = "dlL:Out" input = "mixR:In 2" }"#));
        assert!(c.contains(r#"{ output = "clarR:Out" input = "cpR:In" }"#));
        // Balanced braces / brackets.
        assert_eq!(c.matches('{').count(), c.matches('}').count());
        assert_eq!(c.matches('[').count(), c.matches(']').count());
    }

    #[test]
    fn mic_config_reflects_options() {
        let m = MicSettings { transient_suppression: false, ..Default::default() };
        let c = render_mic_config(&m, Some("alsa_input.x"), None);
        assert!(c.contains("webrtc.transient_suppression = false"));
        assert!(c.contains("webrtc.noise_suppression = true"));
        assert!(c.contains(r#"target.object = "alsa_input.x""#));
        assert_eq!(c.matches('{').count(), c.matches('}').count());
    }
}
